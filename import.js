function splitCsvLine(line) {
    const fields = [];
    let current = "";
    let inQuotes = false;

    for (let i = 0; i < line.length; i++) {
        const char = line[i];

        if (char === '"') {
            if (inQuotes && line[i + 1] === '"') {
                current += '"';
                i++;
            } else {
                inQuotes = !inQuotes;
            }
        } else if (char === "," && !inQuotes) {
            fields.push(current.trim());
            current = "";
        } else {
            current += char;
        }
    }

    fields.push(current.trim());
    return fields;
}

//Turn CSV text into an array of objects keyed by column header
function parseCsv(text) {
    const lines = text.trim().split("\n");
    const headers = splitCsvLine(lines[0]);
    const rows = [];

    for (let i = 1; i < lines.length; i++) {
        const values = splitCsvLine(lines[i]);
        const row = {};

        for (let j = 0; j < headers.length; j++) {
            row[headers[j]] = values[j] || "";
        }

        rows.push(row);
    }
    return rows;
}

//// Discogs appends "(2)" to disambiguate same-named artists and labels.
function stripDiscogsSuffix(text) {
    return text.replace(/\s*\(\d+\)$/, "")
}
// "8/8/26" -> "2026-08-08"
function toIsoDate(text) {
    const parts = text.split("/");

    if (parts.length !== 3) {
        return "";
    }

    const month = parts[0].padStart(2, "0");
    const day = parts[1].padStart(2, "0");
    const year = "20" + parts[2];

    return `${year}-${month}-${day}`;
}

// Convert one parsed CSV row into a record object.
function rowToRecord(row, index) {
    return {
        id: Date.now() + index,
        releaseId: Number(row.release_id),
        artist: stripDiscogsSuffix(row.Artist),
        album: row.Title,
        year: Number(row.Released),
        genre: row.Genre,
        subgenre: row.Subgenre,
        label: stripDiscogsSuffix(row.Label),
        format: row.Format,
        rating: Number(row.Rating),
        status: "owned",
        mediaCondition: row["Collection Media Condition"],
        sleeveCondition: row["Collection Sleeve Condition"],
        purchasePrice: row["Purchase Price"] ? Number(row["Purchase Price"]) : null,
        purchaseLocation: row.Location,
        dateAdded: toIsoDate(row["Date Added"])
    };
}

